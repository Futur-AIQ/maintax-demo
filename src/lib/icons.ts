export type IconName = keyof typeof ICONS;

/** Looks up an icon by name. Unknown names (from data) fall back to Box. */
export function iconFor(name: string): LucideIcon {
  return (ICONS as Record<string, LucideIcon>)[name] ?? Box;
}

interface IconProps extends Omit<LucideProps, "ref"> {
  name: IconName | (string & {});
}

/** `<Icon name="pump" size={18} />`. Decorative by default (aria-hidden), stroke 1.8 like the prototype. */
export function Icon({ name, size = 18, strokeWidth = 1.8, ...rest }: IconProps) {
  return createElement(iconFor(name), { size, strokeWidth, "aria-hidden": true, ...rest });
}
